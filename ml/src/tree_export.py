"""Flatten gradient-boosted tree ensembles into C arrays (ESP32) and JSON (web demo).

Trees are stored in pre-order, so the "true" child is always the next node and only the "false"
child index is kept. Thresholds are stored as float32 and adjusted so the float32 comparison in C
gives exactly the same branch as the library's own comparison on float32 features:

  XGBoost   goes left when  x <  threshold   (threshold is already float32)
  LightGBM  goes left when  x <= threshold   (threshold is float64, so round it down)
"""
import json

import numpy as np


def _to_float32_le(t):
    """Largest float32 <= t, so `x32 <= t32` matches `x32 <= t64`."""
    f = np.float32(t)
    return np.nextafter(f, np.float32(-np.inf)) if float(f) > t else f


def _flatten(trees):
    """trees: list of callables yielding (is_leaf, value|feature, threshold, true_child, false_child)."""
    feat, thr, no, roots = [], [], [], []

    def walk(node):
        idx = len(feat)
        leaf, a, b, left, right = node()
        if leaf:
            feat.append(-1)
            thr.append(float(a))
            no.append(0)
            return idx
        feat.append(int(a))
        thr.append(float(b))
        no.append(0)
        assert walk(left) == idx + 1
        no[idx] = walk(right)
        return idx

    for tree in trees:
        roots.append(walk(tree))
    return np.array(feat, np.int32), np.array(thr, np.float32), np.array(no, np.int64), np.array(roots, np.int64)


def from_xgboost(booster, n_classes, X_ref):
    """Multi-class XGBoost: trees round-robin over classes, softmax over summed leaf values."""
    import xgboost

    def node_of(d):
        def get():
            if "leaf" in d:
                return True, d["leaf"], 0, None, None
            kids = {c["nodeid"]: c for c in d["children"]}
            assert d["missing"] == d["no"]
            return False, int(d["split"][1:]), d["split_condition"], node_of(kids[d["yes"]]), node_of(kids[d["no"]])
        return get

    dumps = [json.loads(t) for t in booster.get_dump(dump_format="json")]
    feat, thr, no, roots = _flatten([node_of(d) for d in dumps])
    ref = booster.predict(xgboost.DMatrix(X_ref), output_margin=True).reshape(len(X_ref), -1)
    mine = _margins_softmax(feat, thr, no, roots, X_ref, n_classes)
    bias = (ref - mine).mean(axis=0)
    err = float(np.abs(ref - mine - bias).max())
    return dict(kind="softmax", n_classes=n_classes, cmp="<", feat=feat, thr=thr, no=no, roots=roots,
                bias=bias.astype(np.float64), max_error=err)


def from_lightgbm(booster, X_ref):
    """Binary LightGBM: probability = sigmoid(sum of leaf values)."""
    model = booster.dump_model()
    assert model["objective"].startswith("binary sigmoid:1"), model["objective"]

    def node_of(d):
        def get():
            if "leaf_value" in d:
                return True, d["leaf_value"], 0, None, None
            assert d["decision_type"] == "<="
            return False, d["split_feature"], _to_float32_le(d["threshold"]), node_of(d["left_child"]), node_of(d["right_child"])
        return get

    feat, thr, no, roots = _flatten([node_of(t["tree_structure"]) for t in model["tree_info"]])
    ref = booster.predict(X_ref, raw_score=True)
    mine = _margins_softmax(feat, thr, no, roots, X_ref, 1, cmp="<=")[:, 0]
    bias = np.array([float((ref - mine).mean())])
    err = float(np.abs(ref - mine - bias[0]).max())
    return dict(kind="sigmoid", n_classes=1, cmp="<=", feat=feat, thr=thr, no=no, roots=roots,
                bias=bias, max_error=err)


def _margins_softmax(feat, thr, no, roots, X, k, cmp="<"):
    out = np.zeros((len(X), k))
    Xf = np.asarray(X, np.float32)
    for t, r in enumerate(roots):
        for s in range(len(Xf)):
            i = r
            while feat[i] >= 0:
                go_left = Xf[s, feat[i]] < thr[i] if cmp == "<" else Xf[s, feat[i]] <= thr[i]
                i = i + 1 if go_left else no[i]
            out[s, t % k] += thr[i]
    return out


def _cfloat(x):
    s = f"{x:.9g}"
    return (s if any(c in s for c in ".en") else s + ".0") + "f"


def emit_c(spec, prefix, title, classes=None, extra_defines=()):
    """C header text. Defines <PREFIX>_* arrays and one inference function."""
    P, p = prefix.upper(), prefix.lower()
    feat, thr, no, roots = spec["feat"], spec["thr"], spec["no"], spec["roots"]
    no_type = "uint16_t" if no.max() < 65536 else "uint32_t"
    join = lambda a, f=str: ",".join(f(x) for x in a)  # noqa: E731
    lines = [
        "// AUTO-GENERATED by ml/scripts/export_model.py - do not edit by hand.",
        f"// {title}",
        f"// {len(roots)} trees, {len(feat)} nodes; flattening error vs the trained model: {spec['max_error']:.2e}",
        "#pragma once",
        "#include <math.h>",
        "#include <stdint.h>",
        "",
    ]
    lines += [f"#define {d}" for d in extra_defines]
    if classes:
        lines += [f"#define {P}_N_CLASSES {len(classes)}",
                  f"static const char *const {P}_CLASSES[{P}_N_CLASSES] = {{" + ",".join(f'"{c}"' for c in classes) + "};"]
    lines += [
        f"#define {P}_N_TREES {len(roots)}",
        f"static const float {P}_BIAS[] = {{" + join(spec["bias"], _cfloat) + "};",
        f"static const uint32_t {P}_ROOT[{len(roots)}] = {{" + join(roots) + "};",
        f"static const int8_t {P}_FEAT[{len(feat)}] = {{" + join(feat) + "};",
        f"static const float {P}_THR[{len(feat)}] = {{" + join(thr, _cfloat) + "};",
        f"static const {no_type} {P}_NO[{len(feat)}] = {{" + join(no) + "};",
        "",
    ]
    cmp = "<" if spec["cmp"] == "<" else "<="
    walk = [
        f"  for (int t = 0; t < {P}_N_TREES; t++) {{",
        f"    uint32_t i = {P}_ROOT[t];",
        f"    while ({P}_FEAT[i] >= 0) i = (x[{P}_FEAT[i]] {cmp} {P}_THR[i]) ? i + 1 : {P}_NO[i];",
    ]
    if spec["kind"] == "sigmoid":
        lines += [f"// Probability of the positive class for a feature vector from crash_features().",
                  f"static inline float {p}_probability(const float *x) {{",
                  f"  float raw = {P}_BIAS[0];"] + walk + [
                  "    raw += " + f"{P}_THR[i];", "  }",
                  "  return 1.0f / (1.0f + expf(-raw));", "}", ""]
    else:
        lines += [f"// Class probabilities (softmax) for a feature vector from crash_features().",
                  f"static inline void {p}_predict(const float *x, float *probs) {{",
                  f"  float margin[{P}_N_CLASSES];",
                  f"  for (int c = 0; c < {P}_N_CLASSES; c++) margin[c] = {P}_BIAS[c];"] + walk + [
                  f"    margin[t % {P}_N_CLASSES] += {P}_THR[i];", "  }",
                  "  float mx = margin[0], sum = 0;",
                  f"  for (int c = 1; c < {P}_N_CLASSES; c++) if (margin[c] > mx) mx = margin[c];",
                  f"  for (int c = 0; c < {P}_N_CLASSES; c++) {{ probs[c] = expf(margin[c] - mx); sum += probs[c]; }}",
                  f"  for (int c = 0; c < {P}_N_CLASSES; c++) probs[c] /= sum;", "}", ""]
    return "\n".join(lines)


def to_dict(spec, **meta):
    d = dict(kind=spec["kind"], cmp=spec["cmp"], n_classes=int(spec["n_classes"]),
             bias=[round(float(b), 7) for b in spec["bias"]], roots=spec["roots"].tolist(),
             feat=spec["feat"].tolist(), thr=[float(f"{x:.9g}") for x in spec["thr"]], no=spec["no"].tolist())
    d.update(meta)
    return d


def flash_kb(spec):
    n = len(spec["feat"])
    return (n * (1 + 4 + (2 if spec["no"].max() < 65536 else 4)) + len(spec["roots"]) * 4) / 1024
